    append_exec(out_dir, f"{PYTHON} experiments/run_v21_01_source_retention.py --scope {args.scope} --shard-index {args.shard_index} --device {args.device} --steps {args.steps}", status="started", note=f"jobs={len(selected)}")
    rows = []
    trace_rows = []
    for job in selected:
        start = time.perf_counter()
        try:
            x_train, y_train, x_val, y_val = load_dataset(str(job["dataset"]), Path(args.data_root), int(args.train_size), int(args.val_size), int(job["seed"]), device, int(args.input_size))
            local = deepcopy(args)
            local.fu_lr = float(job["fu_lr"])
            local.alt_period = int(job["alt_period"])
            local.source_warmup_steps = int(job.get("source_warmup_steps", 0))
            local.source_stop_steps = int(job.get("source_stop_steps", 0))
            local.post_stop_mechanism = str(job.get("post_stop_mechanism", ""))
            local.post_stop_fu_lr = float(job.get("post_stop_fu_lr", local.fu_lr))
            local.optimizer_integration_mode = str(job.get("optimizer_integration_mode", ""))
            local.basis_repair_variant = str(job["basis_repair_variant"])
            train_seed = stable_train_seed(job)
            model = carrier_model(str(job["carrier"]), x_train, train_seed, local, device)
            final, traces, _first_update = train_one(model, str(job["mechanism"]), x_train, y_train, x_val, y_val, local, seed=train_seed)
            rows.append({**job, "train_seed": train_seed, **final, "runtime_sec": time.perf_counter() - start, "execution_status": "measured", "blocker": "", "promotion_allowed": 0})
            for tr in traces:
                trace_rows.append({**job, "train_seed": train_seed, **tr})
        except Exception as exc:
            rows.append({**job, "runtime_sec": time.perf_counter() - start, "execution_status": f"blocked:{type(exc).__name__}", "blocker": str(exc)[:500], "promotion_allowed": 0})
    safe = slug(str(args.run_label or args.scope))
    suffix = f"_{safe}_fc{int(args.shard_index)}"
    write_rows(out_dir / f"v21_01_source_retention_matrix{suffix}.csv", rows)
    write_rows(out_dir / f"v21_01_source_retention_traces{suffix}.csv", trace_rows)
    append_exec(out_dir, f"{PYTHON} experiments/run_v21_01_source_retention.py --scope {args.scope} --shard-index {args.shard_index}", status="completed", note=f"rows={len(rows)} traces={len(trace_rows)}")


