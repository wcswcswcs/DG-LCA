def estimate_effects(events: list[dict[str, Any]], prop_rows: list[dict[str, Any]] | None = None) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    treatment_values: dict[str, list[float]] = {}
    group_values: dict[tuple[str, str, str, str], list[float]] = {}
    for row in events:
        if row.get("status") != "completed_randomized_event":
            continue
        treatment = str(row.get("treatment_selected", ""))
        y = finite_float(row.get("held_train_NLL_delta"))
        if y is None:
            continue
        treatment_values.setdefault(treatment, []).append(float(y))
        group_key = (str(row.get("dataset", "")), str(row.get("seed", "")), str(row.get("architecture", "")), treatment)
        group_values.setdefault(group_key, []).append(float(y))
    estimate_rows: list[dict[str, Any]] = []
    for treatment, vals in sorted(treatment_values.items()):
        match = TREATMENT_META.get(treatment, {}).get("match", "")
        control_vals = treatment_values.get(match, [])
        mean_y = sum(vals) / len(vals)
        mean_c = sum(control_vals) / len(control_vals) if control_vals else 0.0
        tau = mean_y - mean_c
        pooled = vals + control_vals
        if len(pooled) > 1:
            se = statistics.pstdev(pooled) * math.sqrt(1.0 / max(1, len(vals)) + (1.0 / max(1, len(control_vals)) if control_vals else 0.0))
        else:
            se = math.inf
        lcb = tau - 1.64 * se if math.isfinite(se) else -math.inf
        groups_positive = 0
        groups_total = 0
        for (dataset, seed, arch, tr), gvals in group_values.items():
            if tr != treatment:
                continue
            cvals = group_values.get((dataset, seed, arch, match), [])
            if not cvals:
                continue
            groups_total += 1
            if (sum(gvals) / len(gvals)) - (sum(cvals) / len(cvals)) > 0.0:
                groups_positive += 1
        estimate_rows.append(
            {
                "treatment_name": treatment,
                "matched_control": match,
                "treatment_kind": TREATMENT_META.get(treatment, {}).get("kind", ""),
                "n_treatment": len(vals),
                "n_control": len(control_vals),
                "mean_Y_treatment": mean_y,
                "mean_Y_control": mean_c if control_vals else "",
                "tau_hat": tau,
                "SE_hat": se if math.isfinite(se) else "",
                "LCB_0p90": lcb if math.isfinite(lcb) else "",
                "dataset_seed_arch_groups_with_matched_control": groups_total,
                "positive_group_count": groups_positive,
                "positive_group_fraction": groups_positive / groups_total if groups_total else "",
                "pilot_gate_pass": int(
                    TREATMENT_META.get(treatment, {}).get("kind") == "signal"
                    and len(vals) >= 5
                    and len(control_vals) >= 5
                    and math.isfinite(lcb)
                    and lcb > 0.0
                    and groups_positive >= 3
                ),
                "source_artifact": "results/v22_37/v22_37_randomized_event_matrix.csv",
            }
        )
    prop_counts: dict[str, int] = {}
    for row in events:
        tr = str(row.get("treatment_selected", ""))
        if tr:
            prop_counts[tr] = prop_counts.get(tr, 0) + 1
    total = sum(prop_counts.values())
    min_selected_fraction = min((c / total for c in prop_counts.values()), default=0.0)
    if prop_rows is None:
        prop_rows = [r for r in read_rows(OUT_ROOT / "v22_37_propensity_log.csv") if r.get("status") == "logged_before_outcome"]
    else:
        prop_rows = [r for r in prop_rows if r.get("status") == "logged_before_outcome"]
    logged_min_propensity = min((finite_float(r.get("p_min"), 0.0) or 0.0 for r in prop_rows), default=0.0)
    signal_passes = [r for r in estimate_rows if int_flag(r.get("pilot_gate_pass"))]
    controls_with_positive_lcb = [
        r
        for r in estimate_rows
        if r.get("treatment_kind") == "control" and (finite_float(r.get("LCB_0p90"), -math.inf) or -math.inf) > 0.0
    ]
    summary = {
        "completed_randomized_events": total,
        "treatment_count_observed": len(prop_counts),
        "min_selected_fraction": min_selected_fraction,
        "logged_min_propensity": logged_min_propensity,
        "propensity_balance_pass": int(total > 0 and logged_min_propensity >= 0.05),
        "signal_treatment_lcb_pass_rows": len(signal_passes),
        "control_positive_lcb_rows": len(controls_with_positive_lcb),
        "pilot_exploration_pass": int(total >= 300 and logged_min_propensity >= 0.05 and len(signal_passes) >= 1 and len(controls_with_positive_lcb) == 0),
        "status": "estimated" if total else "no_events",
    }
    return estimate_rows, summary


