def enrich_full_loop_rows(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    by_key: dict[tuple[str, str, str, str, str], dict[str, Any]] = {}
    for row in rows:
        key = (
            str(row.get("dataset", "")),
            str(row.get("seed", "")),
            str(row.get("carrier", "")),
            str(row.get("optimizer_family", "")),
            str(row.get("training_variant", "")),
        )
        by_key[key] = row
    enriched = []
    for row in rows:
        out = dict(row)
        base = by_key.get(
            (
                str(row.get("dataset", "")),
                str(row.get("seed", "")),
                str(row.get("carrier", "")),
                str(row.get("optimizer_family", "")),
                "optimizer_alone",
            ),
            {},
        )
        ctrl = by_key.get(
            (
                str(row.get("dataset", "")),
                str(row.get("seed", "")),
                str(row.get("carrier", "")),
                str(row.get("optimizer_family", "")),
                "matched_control_" + str(row.get("treatment_name", "")),
            ),
            {},
        )
        nll = finite_float(row.get("final_test_NLL"))
        base_nll = finite_float(base.get("final_test_NLL"))
        ctrl_nll = finite_float(ctrl.get("final_test_NLL"))
        auc = finite_float(row.get("AUC_loss_time"))
        base_auc = finite_float(base.get("AUC_loss_time"))
        acc = finite_float(row.get("final_test_accuracy"))
        base_acc = finite_float(base.get("final_test_accuracy"))
        ece = finite_float(row.get("ECE"))
        base_ece = finite_float(base.get("ECE"))
        brier = finite_float(row.get("Brier"))
        base_brier = finite_float(base.get("Brier"))
        tail = finite_float(row.get("tail_loss_q99"))
        base_tail = finite_float(base.get("tail_loss_q99"))
        out.update(
            {
                "NLL_delta_vs_own_strong_optimizer": "" if nll is None or base_nll is None else nll - base_nll,
                "AUC_delta_vs_own_strong_optimizer": "" if auc is None or base_auc is None else auc - base_auc,
                "accuracy_delta_vs_own_strong_optimizer": "" if acc is None or base_acc is None else acc - base_acc,
                "NLL_delta_vs_matched_control": "" if nll is None or ctrl_nll is None else nll - ctrl_nll,
                "no_ECE_Brier_tail_debt": int(
                    ece is not None
                    and base_ece is not None
                    and brier is not None
                    and base_brier is not None
                    and tail is not None
                    and base_tail is not None
                    and ece <= base_ece
                    and brier <= base_brier
                    and tail <= base_tail
                )
                if row.get("training_variant", "").startswith("CIFO_FU")
                else "",
            }
        )
        enriched.append(out)
    return enriched


def materialize_gap_truth(full_rows: list[dict[str, Any]], selected_treatment: str) -> list[dict[str, Any]]:
    by_key: dict[tuple[str, str, str, str, str], dict[str, Any]] = {}
    for row in full_rows:
        by_key[
            (
                str(row.get("dataset", "")),
                str(row.get("seed", "")),
                str(row.get("carrier", "")),
                str(row.get("optimizer_family", "")),
                str(row.get("training_variant", "")),
            )
        ] = row
    out_rows: list[dict[str, Any]] = []
    for row in full_rows:
        if row.get("carrier") not in {"D-CHE", "D-FOU"} or row.get("training_variant") != f"CIFO_FU_{selected_treatment}":
            continue
        dataset = str(row.get("dataset", ""))
        seed = str(row.get("seed", ""))
        carrier = str(row.get("carrier", ""))
        opt = str(row.get("optimizer_family", ""))
        kan_base = by_key.get((dataset, seed, carrier, opt, "optimizer_alone"), {})
        kan_fu = row
        mlp_base = by_key.get((dataset, seed, "", opt, "optimizer_alone"), {})
        mlp_fu = by_key.get((dataset, seed, "", opt, f"CIFO_FU_{selected_treatment}"), {})
        vals = [finite_float(r.get("final_test_NLL")) for r in [kan_base, kan_fu, mlp_base, mlp_fu]]
        if any(v is None for v in vals):
            continue
        kan_base_nll, kan_fu_nll, mlp_base_nll, mlp_fu_nll = [float(v) for v in vals if v is not None]
        gap_base = kan_base_nll - mlp_base_nll
        gap_fu = kan_fu_nll - mlp_fu_nll
        gap_reduction = gap_base - gap_fu
        delta_kan = kan_fu_nll - kan_base_nll
        delta_mlp = mlp_fu_nll - mlp_base_nll
        control_delta = finite_float(kan_fu.get("NLL_delta_vs_matched_control"))
        if control_delta is None or control_delta >= 0.0:
            klass = "ControlExplained"
        elif delta_mlp > 0.0 and gap_reduction > 0.0:
            klass = "MLPDegradationDriven"
        elif delta_kan < 0.0 and delta_mlp < 0.0 and gap_reduction > 0.0:
            klass = "BothGain"
        elif delta_kan < 0.0 and delta_mlp <= 0.0 and gap_reduction > 0.0:
            klass = "TrueKANGain"
        else:
            klass = "NoGain"
        out_rows.append(
            {
                "dataset": dataset,
                "seed": seed,
                "optimizer_family": opt,
                "kan_carrier": carrier,
                "selected_treatment": selected_treatment,
                "MLP_strong_NLL": mlp_base_nll,
                "MLP_CIFO_FU_NLL": mlp_fu_nll,
                "KAN_strong_NLL": kan_base_nll,
                "KAN_CIFO_FU_NLL": kan_fu_nll,
                "Delta_MLP_NLL": delta_mlp,
                "Delta_KAN_NLL": delta_kan,
                "Gap_base": gap_base,
                "Gap_FU": gap_fu,
                "GapReduction": gap_reduction,
                "KAN_CIFO_FU_beats_MLP_CIFO_FU": int(kan_fu_nll <= mlp_fu_nll),
                "TrueKANGain_class": klass,
                "status": "completed_gap_truth_compact",
            }
        )
    return out_rows


