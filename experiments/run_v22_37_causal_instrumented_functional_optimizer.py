    gate = int(
        int_flag(source_summary.get("pilot_exploration_pass"))
        and len(selected_treatments) > 0
        and len(controls_open) == 0
        and 0.20 <= noop_rate <= 0.95
    )
    return {
        "policy_gate_pass": gate,
        "policy_noop_rate": noop_rate,
        "policy_training_events": source_summary.get("subset_events", source_summary.get("completed_randomized_events", "")),
        "status": "local_policy_gate_from_treatment_source",
        "source_summary": str(summary_path.relative_to(ROOT)) if summary_path.is_absolute() and summary_path.exists() else str(summary_path),
    }


