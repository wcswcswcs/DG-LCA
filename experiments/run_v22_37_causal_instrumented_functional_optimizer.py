    write_rows(OUT_ROOT / "v22_37_historical_causal_event_matrix.csv", event_rows or [{"status": "no_historical_rows_with_inferable_outcome"}])

    grouped: dict[tuple[str, str], list[float]] = {}
    control_grouped: dict[str, list[float]] = {}
    for row in event_rows:
        y = finite_float(row.get("causal_outcome_y_positive_benefit"))
        if y is None:
            continue
