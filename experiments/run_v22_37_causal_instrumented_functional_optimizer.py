def train_full_loop_variant(
    *,
    dataset: str,
    seed: int,
    architecture: str,
    optimizer_family: str,
    variant: str,
    treatment: str,
    train_loader: Any,
    held_loader: Any,
    test_loader: Any,
    input_dim: int,
    output_dim: int,
    x_stats: Any,
    device: Any,
    args: argparse.Namespace,
    lcb: float,
    source_artifact: str = "results/v22_37/v22_37_causal_effect_estimates.csv",
) -> dict[str, Any]:
    import torch
    import torch.nn.functional as F

    model_seed = int(seed) + 223700 + (0 if architecture == "MLP" else 1000 if architecture == "DGKAN_DCHE" else 2000)
    model = make_model_for_arch(architecture, input_dim, output_dim, int(args.hidden), model_seed, device, x_stats)
    opt = optimizer_for(optimizer_family, model.parameters(), float(args.lr), float(args.weight_decay))
    it = cycle_batches(train_loader)
    loss_trace: list[float] = []
    accepted = 0
    rejected = 0
    candidate_evals = 0
    candidate_delta_sum = 0.0
    accepted_alpha_sum = 0.0
    total_update_norm = 0.0
    basis_update_norm = 0.0
    nonbasis_update_norm = 0.0
    held_it = cycle_batches(held_loader)
    alpha_grid = [float(x) for x in split_csv(getattr(args, "full_loop_alpha_grid", "0"), float)]
    if 0.0 not in alpha_grid:
        alpha_grid = [0.0] + alpha_grid
    start = time.time()
    for step in range(int(args.full_loop_steps)):
        xb, yb = next(it)
        xb = xb.to(device).float()
        yb = yb.to(device).long()
        should_intervene = variant != "optimizer_alone" and (step % max(1, int(args.full_loop_cadence)) == 0)
        chosen_alpha = 0.0
        chosen_update_norm = 0.0
        if should_intervene and str(getattr(args, "full_loop_implementation", "direct")) == "accepted":
            accept_xs = []
            accept_ys = []
            for _ in range(max(1, int(getattr(args, "full_loop_acceptance_batches", 1)))):
                ax_i, ay_i = next(held_it)
                accept_xs.append(ax_i.to(device).float())
                accept_ys.append(ay_i.to(device).long())
            ax = torch.cat(accept_xs, dim=0)
            ay = torch.cat(accept_ys, dim=0)
            branch_seed_base = stable_int_seed("v22_37", dataset, seed, architecture, optimizer_family, variant, step)
            base_loss, _base_norm, base_components = branch_candidate_loss(
                model=model,
                opt=opt,
                architecture=architecture,
                optimizer_family=optimizer_family,
                treatment="a0_base_noop",
                train_xb=xb,
                train_yb=yb,
                accept_xb=ax,
                accept_yb=ay,
                output_dim=output_dim,
                acceptance_metric=str(args.full_loop_acceptance_metric),
                acceptance_tail_quantile=float(getattr(args, "full_loop_acceptance_tail_quantile", 0.90)),
                lr=float(args.lr),
                weight_decay=float(args.weight_decay),
                alpha=0.0,
                seed=branch_seed_base,
            )
            best_loss = base_loss
            best_norm = 0.0
            for alpha in alpha_grid:
                if abs(float(alpha)) <= 0.0:
                    continue
                cand_loss, cand_norm, cand_components = branch_candidate_loss(
                    model=model,
                    opt=opt,
                    architecture=architecture,
                    optimizer_family=optimizer_family,
                    treatment=treatment,
                    train_xb=xb,
                    train_yb=yb,
                    accept_xb=ax,
                    accept_yb=ay,
                    output_dim=output_dim,
                    acceptance_metric=str(args.full_loop_acceptance_metric),
                    acceptance_tail_quantile=float(getattr(args, "full_loop_acceptance_tail_quantile", 0.90)),
                    lr=float(args.lr),
                    weight_decay=float(args.weight_decay),
                    alpha=float(alpha),
                    seed=branch_seed_base + int(abs(float(alpha)) * 1.0e9),
                )
                candidate_evals += 1
                delta = cand_loss - base_loss
                component_ok = True
                if str(args.full_loop_acceptance_metric) == "strict_no_debt":
                    component_ok = (
                        cand_components["ce"] <= base_components["ce"] - float(args.full_loop_acceptance_tol)
                        and cand_components["brier"] <= base_components["brier"] - float(args.full_loop_acceptance_tol)
                        and cand_components["tail"] <= base_components["tail"] - float(args.full_loop_acceptance_tol)
                    )
                elif str(args.full_loop_acceptance_metric) == "strict_ece_no_debt":
                    component_ok = (
                        cand_components["ce"] <= base_components["ce"] - float(args.full_loop_acceptance_tol)
                        and cand_components["ece"] <= base_components["ece"] - float(args.full_loop_acceptance_tol)
                        and cand_components["brier"] <= base_components["brier"] - float(args.full_loop_acceptance_tol)
                        and cand_components["tail"] <= base_components["tail"] - float(args.full_loop_acceptance_tol)
                    )
                if component_ok and cand_loss <= best_loss - float(args.full_loop_acceptance_tol):
                    best_loss = cand_loss
                    chosen_alpha = float(alpha)
                    best_norm = cand_norm
            candidate_delta_sum += best_loss - base_loss
            if chosen_alpha > 0.0 and lcb > float(args.epsilon_row):
                accepted += 1
                accepted_alpha_sum += chosen_alpha
            else:
                rejected += 1
                chosen_alpha = 0.0
                best_norm = 0.0
            train_loss = train_batch_step_with_existing_optimizer(model, opt, optimizer_family, xb, yb)
            loss_trace.append(train_loss)
            if chosen_alpha > 0.0:
                opt.zero_grad(set_to_none=True)
                loss_for_fu = F.cross_entropy(model(xb).float(), yb.long())
                loss_for_fu.backward()
                named, direction, _source = build_treatment_direction(
                    model,
                    opt,
                    architecture,
                    treatment,
                    random.Random(branch_seed_base + 17),
                )
                chosen_update_norm = apply_flat_delta(named, direction, chosen_alpha)
                total_update_norm += chosen_update_norm
                if architecture != "MLP":
                    basis_names = {n for n, _p in named if n in {"w1", "w2"} or n.endswith(".w1") or n.endswith(".w2")}
                    if basis_names:
                        basis_update_norm += chosen_update_norm
                    else:
                        nonbasis_update_norm += chosen_update_norm
                else:
                    nonbasis_update_norm += chosen_update_norm
        else:
            opt.zero_grad(set_to_none=True)
            loss = F.cross_entropy(model(xb).float(), yb)
            loss.backward()
            if should_intervene:
                rng = random.Random(stable_int_seed("direct", dataset, seed, architecture, optimizer_family, variant, step))
                named, direction, _source = build_treatment_direction(model, opt, architecture, treatment, rng)
                chosen_update_norm = apply_flat_delta(named, direction, float(args.intervention_scale))
                total_update_norm += chosen_update_norm
                accepted += 1
                if architecture != "MLP":
                    basis_names = {n for n, _p in named if n in {"w1", "w2"} or n.endswith(".w1") or n.endswith(".w2")}
                    if basis_names:
                        basis_update_norm += chosen_update_norm
                    else:
                        nonbasis_update_norm += chosen_update_norm
                else:
                    nonbasis_update_norm += chosen_update_norm
            if optimizer_family == "Cautious AdamW":
                with torch.no_grad():
                    for group in opt.param_groups:
                        for p in group["params"]:
                            if p.grad is not None:
                                state = opt.state.get(p, {})
                                exp_avg = state.get("exp_avg")
                                if exp_avg is not None:
                                    p.grad.mul_((p.grad * exp_avg >= 0.0).float())
            opt.step()
            loss_trace.append(float(loss.detach().item()))
    if optimizer_family == "Schedule-Free AdamW":
        # Compact local approximation: the run still uses AdamW mechanics, and
        # the implementation level records that this is not the external library.
        pass
    temperature_grid = [max(1.0e-6, float(x)) for x in split_csv(getattr(args, "full_loop_temperature_grid", "1.0"), float)]
    if not temperature_grid:
        temperature_grid = [1.0]
    temperature_metric = str(getattr(args, "full_loop_temperature_selection_metric", "NLL"))
    uncalibrated_test = evaluate_loader_temperature(model, test_loader, device, output_dim, 1.0)
    uncalibrated_held = evaluate_loader_temperature(model, held_loader, device, output_dim, 1.0)
    calibration_temperature, final_held = select_temperature(
        model,
        held_loader,
        device,
        output_dim,
        temperature_grid,
        temperature_metric,
    )
    final_test = evaluate_loader_temperature(model, test_loader, device, output_dim, calibration_temperature)
    elapsed = time.time() - start
    denom = max(1.0e-12, basis_update_norm + nonbasis_update_norm)
