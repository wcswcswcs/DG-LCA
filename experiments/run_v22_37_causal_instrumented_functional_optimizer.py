def run_all(args: argparse.Namespace) -> dict[str, Any]:
    stage_a_code_truth_gate()
    stage_b_historical_reanalysis()
    primary = stage_c_randomized_pilot(args, fallback_label="primary", top3=False)
    stage_d_causal_estimator(args)
    if int(primary.get("events_completed_total", 0)) < 300 or not int_flag((read_rows(OUT_ROOT / "v22_37_causal_policy_calibration.csv") or [{}])[0].get("policy_gate_pass")):
        old_events = int(args.pilot_events_per_group)
        old_horizons = args.pilot_horizons
        # Plan fallback 1: check propensity is materialized by estimator/policy rows.
        # Plan fallback 2/4: increase event count and shrink to top-3 families.
        args.pilot_events_per_group = str(max(int(args.fallback_events_per_group), int(args.pilot_events_per_group)))
        args.pilot_horizons = args.fallback_horizons
        stage_c_randomized_pilot(args, fallback_label="fallback_top3_more_events", top3=True)
        args.pilot_events_per_group = str(old_events)
        args.pilot_horizons = old_horizons
        stage_d_causal_estimator(args)
    if not int_flag((read_rows(OUT_ROOT / "v22_37_causal_policy_calibration.csv") or [{}])[0].get("policy_gate_pass")) and args.long_horizon_fallback:
        old_events = args.pilot_events_per_group
        old_horizons = args.pilot_horizons
        old_datasets = args.pilot_datasets
        old_arch = args.pilot_architectures
        args.pilot_events_per_group = str(max(1, int(args.long_horizon_events_per_group)))
        args.pilot_horizons = args.long_horizon_fallback
        args.pilot_datasets = args.long_horizon_datasets
        args.pilot_architectures = args.long_horizon_architectures
        stage_c_randomized_pilot(args, fallback_label="fallback_long_horizon", top3=True)
        args.pilot_events_per_group = old_events
        args.pilot_horizons = old_horizons
        args.pilot_datasets = old_datasets
        args.pilot_architectures = old_arch
        stage_d_causal_estimator(args)
    stage_e_f_g_full_loop(args)
    stage_h_continual_memory(args)
    stage_figures_and_efficiency()
    return finalize_route(args)


