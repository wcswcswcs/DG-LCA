def evaluate_loader_temperature(model: Any, loader: Any, device: Any, output_dim: int, temperature: float) -> dict[str, float]:
    import torch
    import torch.nn.functional as F

    model.eval()
    total = 0
    correct = 0
    losses_all = []
    logits_all = []
    labels_all = []
    temp = max(1.0e-6, float(temperature))
    with torch.no_grad():
        for xb, yb in loader:
            xb = xb.to(device).float()
            yb = yb.to(device).long()
            logits = model(xb).float() / temp
            loss = F.cross_entropy(logits, yb, reduction="none")
            losses_all.append(loss.detach().cpu())
            logits_all.append(logits.detach().cpu())
            labels_all.append(yb.detach().cpu())
            total += int(yb.numel())
            correct += int((logits.argmax(dim=-1) == yb).sum().item())
    if total == 0:
        return {
            "NLL": math.nan,
            "accuracy": math.nan,
            "ECE": math.nan,
            "Brier": math.nan,
            "tail_q95": math.nan,
            "tail_q99": math.nan,
            "margin_mean": math.nan,
            "margin_q10": math.nan,
            "margin_q01": math.nan,
            "low_margin_accuracy": math.nan,
        }
    losses = torch.cat(losses_all)
    logits = torch.cat(logits_all)
    labels = torch.cat(labels_all)
    probs = torch.softmax(logits.float(), dim=-1)
    target = F.one_hot(labels, num_classes=output_dim).float()
    conf, pred = probs.max(dim=-1)
    ok = (pred == labels).float()
    true_logits = logits.gather(1, labels.view(-1, 1)).squeeze(1)
    masked_logits = logits.clone()
    masked_logits[torch.arange(labels.numel()), labels] = -float("inf")
    next_logits = masked_logits.max(dim=-1).values
    margins = (true_logits - next_logits).float()
    low_margin_mask = margins <= 0.0
    low_margin_accuracy = ok[low_margin_mask].mean() if low_margin_mask.any() else torch.tensor(1.0)
    ece = torch.tensor(0.0)
    for lo in torch.linspace(0, 0.9, 10):
        hi = lo + 0.1
        mask = (conf >= lo) & (conf < hi if hi < 1.0 else conf <= hi)
        if mask.any():
            ece = ece + mask.float().mean() * (conf[mask].mean() - ok[mask].mean()).abs()
    return {
        "NLL": float(losses.mean().item()),
        "accuracy": float(correct / total),
        "ECE": float(ece.item()),
        "Brier": float(((probs - target) ** 2).sum(dim=-1).mean().item()),
        "tail_q95": float(torch.quantile(losses.float(), 0.95).item()),
        "tail_q99": float(torch.quantile(losses.float(), 0.99).item()),
        "margin_mean": float(margins.mean().item()),
        "margin_q10": float(torch.quantile(margins, 0.10).item()),
        "margin_q01": float(torch.quantile(margins, 0.01).item()),
        "low_margin_accuracy": float(low_margin_accuracy.item()),
    }


def temperature_score(metrics: dict[str, float], metric: str) -> float:
    if metric == "NLL":
        return float(metrics["NLL"])
    if metric == "Brier":
        return float(metrics["Brier"])
    if metric == "tail_q99":
        return float(metrics["tail_q99"])
    if metric == "ECE_Brier_tail":
        return float(metrics["ECE"] + 0.25 * metrics["Brier"] + 0.05 * metrics["tail_q99"])
    if metric == "NLL_Brier_tail":
        return float(metrics["NLL"] + 0.25 * metrics["Brier"] + 0.05 * metrics["tail_q99"])
    raise ValueError(f"unknown temperature_selection_metric={metric!r}")


def select_temperature(model: Any, held_loader: Any, device: Any, output_dim: int, grid: list[float], metric: str) -> tuple[float, dict[str, float]]:
    best_temp = 1.0
    best_metrics = evaluate_loader_temperature(model, held_loader, device, output_dim, 1.0)
    best_score = temperature_score(best_metrics, metric)
    for temp in grid:
        metrics = evaluate_loader_temperature(model, held_loader, device, output_dim, float(temp))
        score = temperature_score(metrics, metric)
        if score < best_score:
            best_score = score
            best_temp = float(temp)
            best_metrics = metrics
    return best_temp, best_metrics


