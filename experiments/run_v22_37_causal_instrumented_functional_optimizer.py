    event_rows: list[dict[str, Any]] = []
    scanned_files = 0
    for src_dir in historical_source_dirs():
        for path in sorted(src_dir.glob("*.csv")):
            if path.name.endswith("command_journal.csv"):
                continue
            rows = read_rows(path)
            if not rows:
                continue
            scanned_files += 1
            for idx, row in enumerate(rows[:max_rows_per_file]):
                outcome = infer_outcome(row)
                if outcome is None:
                    continue
                treatment, control_level = infer_treatment(path, row)
