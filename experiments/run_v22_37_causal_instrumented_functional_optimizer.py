    control_explained_rows = sum(1 for r in completed_gap_rows if r.get("TrueKANGain_class") == "ControlExplained")
    gap_gain_fraction = (true_gain_rows + both_gain_rows) / max(1, len(completed_gap_rows))
    mlp_degradation_fraction = mlp_degradation_rows / max(1, len(completed_gap_rows))
    control_explained_fraction = control_explained_rows / max(1, len(completed_gap_rows))
    basis_signal_rows = [
        r
        for r in basis_rows
        if str(r.get("training_variant", "")).startswith("CIFO_FU")
        and r.get("treatment_name") == "a2_basis_actuator_section"
    ]
    kan_internal_rows = len(basis_signal_rows)
    kan_internal_wins = sum(1 for r in basis_signal_rows if (finite_float(r.get("NLL_delta_vs_own_strong_optimizer"), 0.0) or 0.0) < 0.0)
    kan_internal_control_wins = sum(1 for r in basis_signal_rows if (finite_float(r.get("NLL_delta_vs_matched_control"), math.inf) or math.inf) < 0.0)
