def stage_h_continual_memory(args: argparse.Namespace) -> dict[str, Any]:
    import torch
    import torch.nn.functional as F
    from torch.utils.data import DataLoader, Subset
    from torchvision import datasets, transforms

    ensure_out()
    device = torch_device(args.continual_device)
    rows: list[dict[str, Any]] = []
    try:
        transform = transforms.Compose([transforms.ToTensor(), transforms.Lambda(lambda x: x.view(-1))])
        train_ds = datasets.MNIST(root=str(ROOT / "data"), train=True, transform=transform, download=False)
        test_ds = datasets.MNIST(root=str(ROOT / "data"), train=False, transform=transform, download=False)
        seeds_arg = getattr(args, "continual_seeds", "")
        seeds = split_csv(seeds_arg, int) if str(seeds_arg).strip() else [int(args.continual_seed)]
        for seed in seeds:
            seed_rows: list[dict[str, Any]] = []
            rng = random.Random(int(seed))
            task0_train = [i for i, y in enumerate(train_ds.targets.tolist()) if int(y) in {0, 1}]
            task1_train = [i for i, y in enumerate(train_ds.targets.tolist()) if int(y) in {2, 3}]
            task0_test = [i for i, y in enumerate(test_ds.targets.tolist()) if int(y) in {0, 1}]
            task1_test = [i for i, y in enumerate(test_ds.targets.tolist()) if int(y) in {2, 3}]
            rng.shuffle(task0_train)
            rng.shuffle(task1_train)
            rng.shuffle(task0_test)
            rng.shuffle(task1_test)
            train0 = DataLoader(Subset(train_ds, task0_train[: int(args.continual_train_size)]), batch_size=int(args.batch_size), shuffle=True)
            train1 = DataLoader(Subset(train_ds, task1_train[: int(args.continual_train_size)]), batch_size=int(args.batch_size), shuffle=True)
            test0 = DataLoader(Subset(test_ds, task0_test[: int(args.continual_held_size)]), batch_size=int(args.batch_size), shuffle=False)
            test1 = DataLoader(Subset(test_ds, task1_test[: int(args.continual_held_size)]), batch_size=int(args.batch_size), shuffle=False)
            x_stats = next(iter(train0))[0]
            for variant in ["base", "boundary_signal", "same_support_random_control"]:
                model = make_model_for_arch("MLP", 784, 10, int(args.hidden), int(seed) + 9100, device, x_stats)
                opt = optimizer_for("AdamW", model.parameters(), float(args.lr), float(args.weight_decay))
                it = cycle_batches(train0)
                for _ in range(int(args.continual_steps_per_task)):
                    xb, yb = next(it)
                    optimizer_step_with_family(model, opt, "AdamW", xb.to(device).float(), yb.to(device).long())
                before = evaluate_loader(model, test0, device, 10)
                if variant != "base":
                    xb, yb = next(cycle_batches(train0))
                    xb = xb.to(device).float()
                    yb = yb.to(device).long()
                    opt.zero_grad(set_to_none=True)
                    loss = F.cross_entropy(model(xb).float(), yb)
                    loss.backward()
                    named, direction, _source = build_treatment_direction(
                        model,
                        opt,
                        "MLP",
                        "a4_continual_boundary_memory" if variant == "boundary_signal" else "a5_same_support_random",
                        random.Random(int(seed) + 42),
                    )
                    apply_flat_delta(named, direction, float(args.intervention_scale))
                it = cycle_batches(train1)
                for _ in range(int(args.continual_steps_per_task)):
                    xb, yb = next(it)
                    optimizer_step_with_family(model, opt, "AdamW", xb.to(device).float(), yb.to(device).long())
                after0 = evaluate_loader(model, test0, device, 10)
                after1 = evaluate_loader(model, test1, device, 10)
                seed_rows.append(
                    {
                        "dataset": "Class_MNIST_01_to_23",
                        "seed": int(seed),
                        "variant": variant,
                        "old_task_accuracy_before_new_task": before["accuracy"],
                        "old_task_accuracy_after_new_task": after0["accuracy"],
                        "new_task_accuracy": after1["accuracy"],
                        "average_forgetting": before["accuracy"] - after0["accuracy"],
                        "relative_forgetting_reduction": "",
                        "backward_transfer": after0["accuracy"] - before["accuracy"],
                        "boundary_treatment_propensity": 1.0 / 3.0,
                        "boundary_tau_hat": "",
                        "boundary_LCB": "",
                        "slow_signal_spectrum": "",
                        "reservoir_to_signal_migration_index": "",
                        "status": "completed_continual_probe",
                    }
                )
            base_forget = finite_float(next((r["average_forgetting"] for r in seed_rows if r["variant"] == "base"), ""))
            for row in seed_rows:
                if row["variant"] != "base" and base_forget is not None and base_forget != 0.0:
                    row["relative_forgetting_reduction"] = (base_forget - float(row["average_forgetting"])) / abs(base_forget)
            signal_row = next((r for r in seed_rows if r["variant"] == "boundary_signal"), {})
            control_row = next((r for r in seed_rows if r["variant"] == "same_support_random_control"), {})
            if signal_row and control_row:
                tau = float(control_row["average_forgetting"]) - float(signal_row["average_forgetting"])
                signal_row["boundary_tau_hat"] = tau
                signal_row["boundary_LCB"] = tau
            rows.extend(seed_rows)
    except Exception as exc:
        rows.append({"status": "data_unavailable_or_run_failed", "error_type": type(exc).__name__, "error_message": str(exc)})
    write_rows(OUT_ROOT / "v22_37_continual_memory_matrix.csv", rows)
    append_exec(
        "stage_h_continual_memory",
        task_id="H_continual_memory",
        status="pass" if rows and rows[0].get("status") == "completed_continual_probe" else "warn",
        gpu=str(args.continual_device),
        files="results/v22_37/v22_37_continual_memory_matrix.csv",
        note=f"rows={len(rows)}",
    )
    return {"rows": len(rows), "status": rows[0].get("status", "") if rows else "no_rows"}


def write_simple_svg(path: Path, title: str, rows: list[dict[str, Any]], label_key: str, value_key: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    vals = []
    for row in rows[:20]:
        val = finite_float(row.get(value_key), 0.0)
        vals.append((str(row.get(label_key, ""))[:26], float(val or 0.0)))
    width = 900
    height = max(220, 60 + 28 * max(1, len(vals)))
    max_abs = max([abs(v) for _l, v in vals] + [1.0])
    zero = 360
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="20" y="28" font-family="Arial" font-size="18">{title}</text>',
        f'<line x1="{zero}" y1="45" x2="{zero}" y2="{height - 20}" stroke="#444" stroke-width="1"/>',
    ]
    for i, (label, val) in enumerate(vals):
        y = 62 + i * 28
        bar = int((val / max_abs) * 260)
        x = zero if bar >= 0 else zero + bar
        color = "#2f7f5f" if bar >= 0 else "#b44d4d"
        lines.append(f'<text x="20" y="{y + 14}" font-family="Arial" font-size="11">{label}</text>')
        lines.append(f'<rect x="{x}" y="{y}" width="{abs(bar)}" height="18" fill="{color}" opacity="0.85"/>')
        lines.append(f'<text x="{zero + bar + (6 if bar >= 0 else -80)}" y="{y + 14}" font-family="Arial" font-size="11">{val:.4g}</text>')
    lines.append("</svg>")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


