def local_policy_gate_from_estimates(estimates_path: str | Path, selected_treatments: list[dict[str, Any]]) -> dict[str, Any]:
    path = Path(estimates_path)
    if not path.is_absolute():
        path = ROOT / path
    rows = read_rows(path)
    signal_open = [
        r
        for r in rows
        if r.get("treatment_kind") == "signal"
        and int_flag(r.get("pilot_gate_pass"))
        and (finite_float(r.get("LCB_0p90"), -math.inf) or -math.inf) > 0.0
    ]
    controls_open = [
        r
        for r in rows
        if r.get("treatment_kind") == "control" and (finite_float(r.get("LCB_0p90"), -math.inf) or -math.inf) > 0.0
    ]
    noop_rate = 1.0 - min(1.0, len(selected_treatments) / max(1, len(signal_open)))
