def flatten_tensors(named_params: list[tuple[str, Any]], attr: str, opt: Any | None = None) -> Any:
    import torch

    parts = []
    for _name, p in named_params:
        tensor = None
        if attr == "grad":
            tensor = p.grad
        elif attr == "exp_avg" and opt is not None:
            state = opt.state.get(p, {})
            tensor = state.get("exp_avg")
        if tensor is None:
            parts.append(torch.zeros_like(p).reshape(-1))
        else:
            parts.append(tensor.detach().reshape(-1).clone())
    return torch.cat(parts) if parts else torch.empty(0)


def apply_flat_delta(named_params: list[tuple[str, Any]], flat_delta: Any, scale: float) -> float:
    import torch

    offset = 0
    norm2 = 0.0
    with torch.no_grad():
        for _name, p in named_params:
            n = p.numel()
            delta = flat_delta[offset : offset + n].view_as(p).to(device=p.device, dtype=p.dtype) * float(scale)
            p.add_(delta)
            norm2 += float(delta.norm().item()) ** 2
            offset += n
    return math.sqrt(norm2)


def stable_int_seed(*parts: Any) -> int:
    text = "|".join(str(p) for p in parts)
    return int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:12], 16) % (2**31 - 1)


def normalized_direction(vec: Any) -> Any:
    norm = float(vec.norm().item()) if vec.numel() else 0.0
    if norm <= 0.0 or not math.isfinite(norm):
        return vec * 0.0
    return vec / norm


def batch_ce_loss(model: Any, xb: Any, yb: Any) -> float:
    import torch
    import torch.nn.functional as F

    with torch.no_grad():
        return float(F.cross_entropy(model(xb).float(), yb.long()).detach().item())


def batch_acceptance_score(model: Any, xb: Any, yb: Any, output_dim: int, metric: str, tail_quantile: float = 0.90) -> float:
    import torch
    import torch.nn.functional as F

    with torch.no_grad():
        logits = model(xb).float()
        losses = F.cross_entropy(logits, yb.long(), reduction="none")
        ce = losses.mean()
        if metric == "ce":
            return float(ce.item())
        probs = torch.softmax(logits, dim=-1)
        target = F.one_hot(yb.long(), num_classes=int(output_dim)).float()
        brier = ((probs - target) ** 2).sum(dim=-1).mean()
        tail = torch.quantile(losses.float(), min(0.999, max(0.50, float(tail_quantile))))
        if metric == "ce_brier":
            return float((ce + 0.25 * brier).item())
        if metric == "ce_brier_tail":
            return float((ce + 0.25 * brier + 0.05 * tail).item())
        if metric == "strict_no_debt":
            return float((ce + 0.25 * brier + 0.05 * tail).item())
        raise ValueError(f"unknown full_loop_acceptance_metric={metric!r}")


def batch_acceptance_components(model: Any, xb: Any, yb: Any, output_dim: int, metric: str, tail_quantile: float = 0.90) -> dict[str, float]:
    import torch
    import torch.nn.functional as F

    with torch.no_grad():
        logits = model(xb).float()
        losses = F.cross_entropy(logits, yb.long(), reduction="none")
        ce = losses.mean()
        probs = torch.softmax(logits, dim=-1)
        target = F.one_hot(yb.long(), num_classes=int(output_dim)).float()
        brier = ((probs - target) ** 2).sum(dim=-1).mean()
        tail = torch.quantile(losses.float(), min(0.999, max(0.50, float(tail_quantile))))
        if metric == "ce":
            score = ce
        elif metric == "ce_brier":
            score = ce + 0.25 * brier
        elif metric in {"ce_brier_tail", "strict_no_debt"}:
            score = ce + 0.25 * brier + 0.05 * tail
        elif metric == "strict_ece_no_debt":
            conf, pred = probs.max(dim=-1)
            ok = (pred == yb.long()).float()
            ece = torch.tensor(0.0, device=logits.device)
            for lo in torch.linspace(0, 0.9, 10, device=logits.device):
                hi = lo + 0.1
                mask = (conf >= lo) & ((conf < hi) if float(hi.item()) < 1.0 else (conf <= hi))
                if mask.any():
                    ece = ece + mask.float().mean() * (conf[mask].mean() - ok[mask].mean()).abs()
            score = ce + 0.25 * brier + 0.05 * tail + 0.50 * ece
        else:
            raise ValueError(f"unknown full_loop_acceptance_metric={metric!r}")
        if metric != "strict_ece_no_debt":
            conf, pred = probs.max(dim=-1)
            ok = (pred == yb.long()).float()
            ece = torch.tensor(0.0, device=logits.device)
            for lo in torch.linspace(0, 0.9, 10, device=logits.device):
                hi = lo + 0.1
                mask = (conf >= lo) & ((conf < hi) if float(hi.item()) < 1.0 else (conf <= hi))
                if mask.any():
                    ece = ece + mask.float().mean() * (conf[mask].mean() - ok[mask].mean()).abs()
        return {
            "ce": float(ce.item()),
            "ece": float(ece.item()),
            "brier": float(brier.item()),
            "tail": float(tail.item()),
            "tail_quantile": min(0.999, max(0.50, float(tail_quantile))),
            "score": float(score.item()),
        }


def train_batch_step_with_existing_optimizer(model: Any, opt: Any, optimizer_family: str, xb: Any, yb: Any) -> float:
    import torch
    import torch.nn.functional as F

    opt.zero_grad(set_to_none=True)
    loss = F.cross_entropy(model(xb).float(), yb.long())
    loss.backward()
    if optimizer_family == "Cautious AdamW":
        with torch.no_grad():
            for group in opt.param_groups:
                for p in group["params"]:
                    if p.grad is not None:
                        state = opt.state.get(p, {})
                        exp_avg = state.get("exp_avg")
                        if exp_avg is not None:
                            p.grad.mul_((p.grad * exp_avg >= 0.0).float())
    opt.step()
    return float(loss.detach().item())


def branch_candidate_loss(
    *,
    model: Any,
    opt: Any,
    architecture: str,
    optimizer_family: str,
    treatment: str,
    train_xb: Any,
    train_yb: Any,
    accept_xb: Any,
    accept_yb: Any,
    output_dim: int,
    acceptance_metric: str,
    acceptance_tail_quantile: float,
    lr: float,
    weight_decay: float,
    alpha: float,
    seed: int,
) -> tuple[float, float, dict[str, float]]:
    import torch.nn.functional as F

    branch = copy.deepcopy(model)
    branch_opt = optimizer_for(optimizer_family, branch.parameters(), lr, weight_decay)
    clone_optimizer_state(opt, branch_opt)
    branch_opt.zero_grad(set_to_none=True)
    loss = F.cross_entropy(branch(train_xb).float(), train_yb.long())
    loss.backward()
    if optimizer_family == "Cautious AdamW":
        for group in branch_opt.param_groups:
            for p in group["params"]:
                if p.grad is not None:
                    state = branch_opt.state.get(p, {})
                    exp_avg = state.get("exp_avg")
                    if exp_avg is not None:
                        p.grad.mul_((p.grad * exp_avg >= 0.0).float())
    branch_opt.step()
    update_norm = 0.0
    if abs(float(alpha)) > 0.0:
        branch_opt.zero_grad(set_to_none=True)
        loss2 = F.cross_entropy(branch(train_xb).float(), train_yb.long())
        loss2.backward()
        named, direction, _source = build_treatment_direction(
            branch,
            branch_opt,
            architecture,
            treatment,
            random.Random(int(seed)),
        )
        update_norm = apply_flat_delta(named, direction, float(alpha))
    comps = batch_acceptance_components(branch, accept_xb, accept_yb, output_dim, acceptance_metric, acceptance_tail_quantile)
    return comps["score"], update_norm, comps


def build_treatment_direction(model: Any, opt: Any, architecture: str, treatment: str, rng: random.Random) -> tuple[list[tuple[str, Any]], Any, str]:
    import torch

    named = named_trainable(model, architecture, treatment)
    grad = flatten_tensors(named, "grad")
    momentum = flatten_tensors(named, "exp_avg", opt)
    if treatment == "a0_base_noop":
        return named, grad * 0.0, "base_noop"
    if treatment in {"a1_signal_direction", "a2_basis_actuator_section", "a4_continual_boundary_memory"}:
        return named, -normalized_direction(grad), "negative_train_gradient"
    if treatment == "a3_optimizer_state_signal":
        source = momentum if float(momentum.norm().item()) > 0.0 else grad
        return named, -normalized_direction(source), "negative_optimizer_momentum_or_gradient"
    if treatment in {"a5_same_support_random", "a6_same_actuator_random"}:
        gen = torch.Generator(device=grad.device if grad.is_cuda else "cpu")
        gen.manual_seed(rng.randrange(1, 2**31 - 1))
        rand = torch.randn(grad.shape, generator=gen, device=grad.device, dtype=grad.dtype)
        return named, normalized_direction(rand), "norm_matched_random"
    if treatment == "a7_same_optimizer_geometry":
        source = momentum if float(momentum.norm().item()) > 0.0 else grad
        if source.numel() > 1:
            perm = torch.randperm(source.numel(), generator=torch.Generator(device=source.device).manual_seed(rng.randrange(1, 2**31 - 1)), device=source.device)
            source = source[perm]
        return named, -normalized_direction(source), "shuffled_optimizer_geometry"
    return named, grad * 0.0, "unknown_noop"


def optimizer_step_with_family(model: Any, opt: Any, optimizer_family: str, xb: Any, yb: Any) -> float:
    import torch
    import torch.nn.functional as F

    opt.zero_grad(set_to_none=True)
    loss = F.cross_entropy(model(xb).float(), yb.long())
    loss.backward()
    if optimizer_family == "Cautious AdamW":
        with torch.no_grad():
            for group in opt.param_groups:
                for p in group["params"]:
                    if p.grad is not None:
                        state = opt.state.get(p, {})
                        exp_avg = state.get("exp_avg")
                        if exp_avg is not None:
                            p.grad.mul_((p.grad * exp_avg >= 0.0).float())
    opt.step()
    return float(loss.detach().item())


def run_micro_event(
    *,
    dataset: str,
    seed: int,
    architecture: str,
    optimizer_family: str,
    event_idx: int,
    treatment: str,
    valid_treatments: list[str],
    device: Any,
    train_loader: Any,
    held_loader: Any,
    output_dim: int,
    model: Any,
    opt: Any,
    train_it: Any,
    hidden: int,
    lr: float,
    weight_decay: float,
    horizon: int,
    intervention_scale: float,
    rng: random.Random,
    meta: dict[str, Any],
) -> tuple[dict[str, Any], dict[str, Any]]:
    import torch
    import torch.nn.functional as F

    xb, yb = next(train_it)
    xb = xb.to(device).float()
    yb = yb.to(device).long()
    opt.zero_grad(set_to_none=True)
    loss = F.cross_entropy(model(xb).float(), yb)
    loss.backward()
    selected_named = named_trainable(model, architecture, treatment)
    grad_flat = flatten_tensors(selected_named, "grad")
    grad_norm = float(grad_flat.norm().item()) if grad_flat.numel() else 0.0
    signal_eigenvalue = float((grad_norm ** 2) / max(1, grad_flat.numel()))
    held_before = evaluate_loader(model, held_loader, device, output_dim)
    base_model = copy.deepcopy(model).to(device)
    treat_model = copy.deepcopy(model).to(device)
    base_opt = optimizer_for(optimizer_family, base_model.parameters(), lr, weight_decay)
    treat_opt = optimizer_for(optimizer_family, treat_model.parameters(), lr, weight_decay)
    clone_optimizer_state(opt, base_opt)
    clone_optimizer_state(opt, treat_opt)
    # Recompute gradients on the treatment branch at the exact event state.
    treat_opt.zero_grad(set_to_none=True)
    treat_loss = F.cross_entropy(treat_model(xb).float(), yb)
    treat_loss.backward()
    named, direction, source_name = build_treatment_direction(treat_model, treat_opt, architecture, treatment, rng)
    update_norm = apply_flat_delta(named, direction, intervention_scale)
    shared_batches = []
    for _ in range(int(horizon)):
        hx, hy = next(train_it)
        shared_batches.append((hx.to(device).float(), hy.to(device).long()))
    start = time.time()
    base_loss_trace = []
    treat_loss_trace = []
    for hx, hy in shared_batches:
        base_loss_trace.append(optimizer_step_with_family(base_model, base_opt, optimizer_family, hx, hy))
        treat_loss_trace.append(optimizer_step_with_family(treat_model, treat_opt, optimizer_family, hx, hy))
    elapsed = time.time() - start
    base_after = evaluate_loader(base_model, held_loader, device, output_dim)
    treat_after = evaluate_loader(treat_model, held_loader, device, output_dim)
    opt.step()
    y_positive = float(base_after["NLL"] - treat_after["NLL"])
    propensity = 1.0 / float(len(valid_treatments))
    propensity_vector = {t: propensity for t in valid_treatments}
    state_z = {
        "signal_eigenvalue_proxy": signal_eigenvalue,
        "grad_norm": grad_norm,
        "held_before_NLL": held_before.get("NLL"),
        "task_tier": meta.get("task_tier", ""),
        "architecture": architecture,
        "optimizer_family": optimizer_family,
        "horizon": horizon,
    }
    state_z_text = json.dumps(state_z, sort_keys=True)
    event_id = f"{dataset}_s{seed}_{architecture}_{safe_fragment(optimizer_family)}_e{event_idx:05d}_H{horizon}"
    event_row = {
        "event_id": event_id,
        "checkpoint_id": f"rolling_step_{event_idx}",
        "dataset": dataset,
        "seed": seed,
        "architecture": architecture,
        "carrier": carrier_for_arch(architecture),
        "optimizer_family": optimizer_family,
        "state_z_hash": hashlib.sha256(state_z_text.encode("utf-8")).hexdigest(),
        "state_z_json": state_z_text,
        "eligible_reason": "train_stream_micro_intervention_event",
        "propensity_vector": json.dumps(propensity_vector, sort_keys=True),
        "treatment_selected": treatment,
        "control_matched_family": TREATMENT_META.get(treatment, {}).get("match", ""),
        "treatment_kind": TREATMENT_META.get(treatment, {}).get("kind", ""),
        "propensity": propensity,
        "applied_update_norm": update_norm,
        "applied_update_support": ",".join(n for n, _p in named[:12]),
        "basis_bank": carrier_for_arch(architecture),
        "H": horizon,
        "H20_outcome": y_positive if horizon == 20 else "",
        "H60_outcome": y_positive if horizon == 60 else "",
        "H200_outcome": y_positive if horizon == 200 else "",
        "H800_outcome": y_positive if horizon == 800 else "",
        "held_train_NLL_base_after": base_after["NLL"],
        "held_train_NLL_treatment_after": treat_after["NLL"],
        "held_train_NLL_delta": y_positive,
        "hard_slice_NLL_delta": y_positive,
        "ECE_delta": float(base_after["ECE"] - treat_after["ECE"]),
        "Brier_delta": float(base_after["Brier"] - treat_after["Brier"]),
        "tail_q99_delta": float(base_after["tail_q99"] - treat_after["tail_q99"]),
        "margin_q10_delta": float(treat_after["margin_q10"] - base_after["margin_q10"]),
        "sharpness_delta": "",
        "wallclock_overhead": elapsed / max(1, horizon),
        "direction_source": source_name,
        "base_horizon_loss_mean": sum(base_loss_trace) / max(1, len(base_loss_trace)),
        "treatment_horizon_loss_mean": sum(treat_loss_trace) / max(1, len(treat_loss_trace)),
        "status": "completed_randomized_event",
        "source_artifact": "direct_v22_37_randomized_micro_intervention",
    }
    prop_row = {
        "event_id": event_id,
        "dataset": dataset,
        "seed": seed,
        "architecture": architecture,
        "optimizer_family": optimizer_family,
        "valid_treatment_count": len(valid_treatments),
        "p_min": min(propensity_vector.values()),
        "p_max": max(propensity_vector.values()),
        "propensity_vector": json.dumps(propensity_vector, sort_keys=True),
        "selected": treatment,
        "status": "logged_before_outcome",
    }
    return event_row, prop_row


